pub struct GlyphClassifier;

impl Default for GlyphClassifier {
    fn default() -> Self {
        Self
    }
}

impl GlyphClassifier {
    pub fn new() -> Self {
        Self
    }

    /// Classifies an 8x16 normalized binary glyph against font templates.
    pub fn classify_glyph(&self, bitmap: [u8; 16]) -> (char, f32) {
        let mut best_char = '?';
        let mut best_score = 0.0f32;

        for &(ch, tmpl) in FONT_TEMPLATES {
            let mut inter = 0u32;
            let mut uni = 0u32;
            for r in 0..16 {
                inter += (bitmap[r] & tmpl[r]).count_ones();
                uni += (bitmap[r] | tmpl[r]).count_ones();
            }
            let score = if uni > 0 { inter as f32 / uni as f32 } else { 0.0 };
            if score > best_score {
                best_score = score;
                best_char = ch;
            }
        }

        // Return best matching character with its confidence
        let confidence = (best_score * 1.5).clamp(0.40, 0.99);
        (best_char, confidence)
    }

    /// Segments and recognizes all words and characters in a cropped text line image.
    pub fn recognize_line(&self, line_img: &DynamicImage) -> (String, Vec<Word>, f32) {
        let (w, h) = line_img.dimensions();
        if w < 4 || h < 4 {
            return (String::new(), Vec::new(), 0.0);
        }

        let gray = line_img.to_luma8();

        // Background polarity from edge
        let mut edge_sum = 0u64;
        let mut edge_cnt = 0u64;
        for x in 0..w {
            edge_sum += gray.get_pixel(x, 0)[0] as u64;
            edge_sum += gray.get_pixel(x, h - 1)[0] as u64;
            edge_cnt += 2;
        }
        let bg_thresh = if edge_cnt > 0 { (edge_sum / edge_cnt) as u8 } else { 255 };
        let is_light_bg = bg_thresh > 127;
        let text_diff = 25u8;

        // Vertical projection profile
        let mut col_activity = vec![0u32; w as usize];
        for x in 0..w {
            let mut count = 0u32;
            for y in 0..h {
                let p = gray.get_pixel(x, y)[0];
                let is_text = if is_light_bg {
                    p < bg_thresh.saturating_sub(text_diff)
                } else {
                    p > bg_thresh.saturating_add(text_diff)
                };
                if is_text {
                    count += 1;
                }
            }
            if count >= (h / 20).max(2) {
                col_activity[x as usize] = count;
            }
        }

        // Segment contiguous glyph columns
        let mut glyph_segments = Vec::new();
        let mut in_glyph = false;
        let mut gx0 = 0u32;

        for x in 0..w {
            let active = col_activity[x as usize] > 0;
            if active && !in_glyph {
                in_glyph = true;
                gx0 = x;
            } else if !active && in_glyph {
                in_glyph = false;
                let gw = x - gx0;
                if gw >= 2 {
                    glyph_segments.push((gx0, x));
                }
            }
        }
        if in_glyph {
            let gw = w - gx0;
            if gw >= 2 {
                glyph_segments.push((gx0, w));
            }
        }

        if glyph_segments.is_empty() {
            return (String::new(), Vec::new(), 0.0);
        }

        let mut words = Vec::new();
        let mut current_word_chars = Vec::new();
        let mut current_word_text = String::new();
        let mut line_text = String::new();
        let mut total_conf = 0.0f32;
        let mut total_chars = 0usize;

        let space_threshold = ((h as f32) * 0.28).max(4.0) as u32;

        for i in 0..glyph_segments.len() {
            let (x0, x1) = glyph_segments[i];

            // Detect space before this glyph
            if i > 0 {
                let prev_x1 = glyph_segments[i - 1].1;
                if (x0 - prev_x1) >= space_threshold {
                    if !current_word_chars.is_empty() {
                        let w_min_x = current_word_chars.first().unwrap().bounding_box.as_ref().map(|b| b.x).unwrap_or(0.0);
                        let w_max_x = current_word_chars.last().unwrap().bounding_box.as_ref().map(|b| b.x + b.width).unwrap_or(0.0);
                        let word_conf = current_word_chars.iter().filter_map(|c| c.confidence).sum::<f32>() / current_word_chars.len() as f32;
                        words.push(Word {
                            text: current_word_text.clone(),
                            confidence: Some(word_conf),
                            bounding_box: Some(BoundingBox::new(w_min_x, 0.0, w_max_x - w_min_x, h as f64)),
                            polygon: None,
                            characters: current_word_chars.clone(),
                        });
                        current_word_chars.clear();
                        current_word_text.clear();
                        line_text.push(' ');
                    }
                }
            }

            // Determine vertical extent of this glyph
            let mut min_y = h;
            let mut max_y = 0;
            for y in 0..h {
                for x in x0..x1 {
                    let p = gray.get_pixel(x, y)[0];
                    let is_text = if is_light_bg {
                        p < bg_thresh.saturating_sub(text_diff)
                    } else {
                        p > bg_thresh.saturating_add(text_diff)
                    };
                    if is_text {
                        if y < min_y { min_y = y; }
                        if y > max_y { max_y = y; }
                    }
                }
            }
            if max_y <= min_y {
                min_y = 0;
                max_y = h;
            }

            // Normalize glyph to 8x16 binary matrix
            let gw = (x1 - x0).max(1);
            let gh = (max_y - min_y + 1).max(1);
            let mut bitmap = [0u8; 16];

            for row in 0..16 {
                let src_y = min_y + (row * gh / 16);
                let mut row_byte = 0u8;
                for col in 0..8 {
                    let src_x = x0 + (col * gw / 8);
                    let p = gray.get_pixel(src_x.min(w - 1), src_y.min(h - 1))[0];
                    let is_text = if is_light_bg {
                        p < bg_thresh.saturating_sub(text_diff)
                    } else {
                        p > bg_thresh.saturating_add(text_diff)
                    };
                    if is_text {
                        row_byte |= 1 << (7 - col);
                    }
                }
                bitmap[row] = row_byte;
            }

            let (ch, conf) = self.classify_glyph(bitmap);
            let char_bbox = BoundingBox::new(x0 as f64, min_y as f64, (x1 - x0) as f64, (max_y - min_y + 1) as f64);

            let character = Character {
                text: ch.to_string(),
                confidence: Some(conf),
                bounding_box: Some(char_bbox),
            };

            current_word_chars.push(character);
            current_word_text.push(ch);
            line_text.push(ch);
            total_conf += conf;
            total_chars += 1;
        }

        // Flush last word
        if !current_word_chars.is_empty() {
            let w_min_x = current_word_chars.first().unwrap().bounding_box.as_ref().map(|b| b.x).unwrap_or(0.0);
            let w_max_x = current_word_chars.last().unwrap().bounding_box.as_ref().map(|b| b.x + b.width).unwrap_or(0.0);
            let word_conf = current_word_chars.iter().filter_map(|c| c.confidence).sum::<f32>() / current_word_chars.len() as f32;
            words.push(Word {
                text: current_word_text,
                confidence: Some(word_conf),
                bounding_box: Some(BoundingBox::new(w_min_x, 0.0, w_max_x - w_min_x, h as f64)),
                polygon: None,
                characters: current_word_chars,
            });
        }

        let avg_conf = if total_chars > 0 { total_conf / total_chars as f32 } else { 0.0 };
        (line_text, words, avg_conf)
    }
}

